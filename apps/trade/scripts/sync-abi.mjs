/**
 * Extract ABI JSON from contracts/out/ and write typed TS files to src/abi/.
 *
 * Usage: node scripts/sync-abi.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const contractsOut = join(__dirname, "../../../contracts/out");
const abiDir = join(__dirname, "../src/abi");

mkdirSync(abiDir, { recursive: true });

const contracts = [
  { name: "dlob", path: "DLOB.sol/DLOB.json" },
  { name: "dlob-factory", path: "DLOBFactory.sol/DLOBFactory.json" },
  { name: "erc20", path: "ERC20.sol/ERC20.json" },
];

for (const { name, path } of contracts) {
  const fullPath = join(contractsOut, path);
  try {
    const json = JSON.parse(readFileSync(fullPath, "utf-8"));
    const abi = JSON.stringify(json.abi, null, 2);
    const constName = name
      .replace(/-([a-z])/g, (_, c) => c.toUpperCase())
      .replace(/^./, (c) => c.toLowerCase()) + "Abi";
    const content = `// SPDX-License-Identifier: MIT\n// SPDX-FileCopyrightText: © 2026 Parity Technologies\n// Auto-generated by scripts/sync-abi.mjs — do not edit\nexport const ${constName} = ${abi} as const;\n`;
    writeFileSync(join(abiDir, `${name}.ts`), content);
    console.log(`✓ ${name}.ts (${json.abi.length} entries)`);
  } catch (e) {
    console.error(`✗ ${name}: ${e.message}`);
    process.exit(1);
  }
}
